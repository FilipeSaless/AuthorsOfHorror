function renderAuthors(authors, typeByTitle = {}) {
    const carousel = document.getElementById('authorsCarousel');
    const dotsContainer = document.getElementById('authorsDots');
    if (!carousel) return;

    // Limpa antes de montar: loadHome() pode rodar de novo (login/logout) e duplicaria os slides.
    carousel.innerHTML = '';
    if (dotsContainer) dotsContainer.innerHTML = '';

    authors.forEach((author, i) => {
        const worksLabel = author.works.length > 1 ? 'Obras' : 'Obra';
        const worksList = author.works.map(w => {
            const type = typeByTitle[w];
            return type
                ? `<li><a class="work-link" href="./detalhes.html?type=${type}&title=${encodeURIComponent(w)}">${w}</a></li>`
                : `<li>${w}</li>`;
        }).join('');
        const slide = document.createElement('article');
        slide.className = 'author-slide';
        slide.dataset.index = i;
        const authorHref = `./detalhes.html?type=author&name=${encodeURIComponent(author.name)}`;
        slide.innerHTML = `
            <a class="author-img-link" href="${authorHref}">
                <img src="${author.image}" alt="${author.name}">
            </a>
            <div class="author-info">
                <h3><a class="author-name-link" href="${authorHref}">${author.name}</a></h3>
                <p>${author.description}</p>
                <div class="author-works">
                    <strong>${worksLabel}:</strong>
                    <ul>${worksList}</ul>
                </div>
            </div>
        `;
        carousel.appendChild(slide);

        const dot = document.createElement('button');
        dot.className = 'authors-dot';
        dot.dataset.index = i;
        dotsContainer?.appendChild(dot);
    });

    let current = 0;
    const total = authors.length;
    const dots = dotsContainer ? dotsContainer.querySelectorAll('.authors-dot') : [];

    const goTo = (index) => {
        current = (index + total) % total;
        carousel.style.transform = `translateX(-${current * 100}%)`;
        dots.forEach((d, i) => d.classList.toggle('active', i === current));
    };
    // Expõe o estado mais recente para handlers que persistem entre renders (hover).
    carousel._goTo = goTo;
    carousel._current = () => current;

    // Timer único persistente: evita múltiplos auto-plays se loadHome() rodar de novo.
    clearInterval(carousel._autoTimer);
    const startAuto = () => {
        clearInterval(carousel._autoTimer);
        carousel._autoTimer = setInterval(() => carousel._goTo(carousel._current() + 1), 7000);
    };
    const restartAuto = () => startAuto();

    // Recria os botões para descartar listeners de renders anteriores.
    [['authorsPrev', -1], ['authorsNext', 1]].forEach(([id, dir]) => {
        const btn = document.getElementById(id);
        if (!btn) return;
        const fresh = btn.cloneNode(true);
        btn.replaceWith(fresh);
        fresh.addEventListener('click', () => { goTo(current + dir); restartAuto(); });
    });

    dots.forEach(dot => {
        dot.addEventListener('click', () => { goTo(Number(dot.dataset.index)); restartAuto(); });
    });

    // Hover pausa/retoma o auto-play; vincula apenas uma vez por elemento.
    const wrapper = carousel.parentElement;
    if (wrapper && !wrapper._hoverBound) {
        wrapper._hoverBound = true;
        wrapper.addEventListener('mouseenter', () => clearInterval(carousel._autoTimer));
        wrapper.addEventListener('mouseleave', () => startAuto());
    }

    goTo(0);
    startAuto();
}

function setupHomeSearch(movies, books, authors) {
    const input = document.querySelector('.search-box input');
    const box = document.querySelector('.search-box');
    if (!input || !box) return;

    const suggestions = document.createElement('ul');
    suggestions.className = 'search-suggestions';
    box.appendChild(suggestions);

    const items = [
        ...movies.map(m => ({ type: 'movie', label: m.title, href: `./detalhes.html?type=movie&title=${encodeURIComponent(m.title)}` })),
        ...books.map(b => ({ type: 'book', label: b.title, href: `./detalhes.html?type=book&title=${encodeURIComponent(b.title)}` })),
        ...authors.map(a => ({ type: 'author', label: a.name, href: `./detalhes.html?type=author&name=${encodeURIComponent(a.name)}` }))
    ];

    const typeLabels = { movie: 'Filme', book: 'Livro', author: 'Autor' };

    const updateSuggestions = (q) => {
        suggestions.innerHTML = '';
        if (!q) { suggestions.classList.remove('visible'); return; }
        const matches = items.filter(i => i.label.toLowerCase().includes(q.toLowerCase())).slice(0, 8);
        if (!matches.length) {
            suggestions.innerHTML = '<li class="no-suggestion">Nenhum resultado encontrado</li>';
        } else {
            matches.forEach(m => {
                const li = document.createElement('li');
                li.innerHTML = `<a href="${m.href}"><span class="suggestion-label">${m.label}</span><span class="suggestion-type">${typeLabels[m.type]}</span></a>`;
                suggestions.appendChild(li);
            });
        }
        suggestions.classList.add('visible');
    };

    const cards = [
        ...document.querySelectorAll('.movies-grid .card'),
        ...document.querySelectorAll('.books-grid .book')
    ];

    const toggleSection = (selector, visible) => {
        const section = document.querySelector(selector);
        if (section) section.style.display = visible ? '' : 'none';
    };

    const applyFilter = (term) => {
        const q = term.trim().toLowerCase();
        let visibleMovies = 0;
        let visibleBooks = 0;
        cards.forEach(card => {
            const title = (card.dataset.title || '').toLowerCase();
            const description = (card.dataset.description || '').toLowerCase();
            const match = !q || title.includes(q) || description.includes(q);
            card.style.display = match ? '' : 'none';
            if (match) {
                if (card.classList.contains('card')) visibleMovies++;
                else visibleBooks++;
            }
        });
        toggleSection('.movies-section', visibleMovies > 0 || !q);
        toggleSection('.books-section', visibleBooks > 0 || !q);
    };

    input.addEventListener('input', e => {
        applyFilter(e.target.value);
        updateSuggestions(e.target.value);
    });
    input.addEventListener('focus', () => {
        if (input.value) updateSuggestions(input.value);
    });
    document.addEventListener('click', e => {
        if (!box.contains(e.target)) suggestions.classList.remove('visible');
    });

    const initial = new URLSearchParams(window.location.search).get('search') || '';
    if (initial) { input.value = initial; applyFilter(initial); }
}

