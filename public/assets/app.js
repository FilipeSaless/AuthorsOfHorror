/* =================== AUTH (sessionStorage) =================== */

function getUser() {
    try { return JSON.parse(sessionStorage.getItem(SESSION_KEY)); }
    catch { return null; }
}

function setUser(user) {
    sessionStorage.setItem(SESSION_KEY, JSON.stringify({
        username: user.username,
        firstName: user.firstName || null,
        avatar: user.avatar || null,
        admin: !!user.admin,
        since: Date.now()
    }));
}

function clearUser() {
    sessionStorage.removeItem(SESSION_KEY);
}

function findCredential(username, password) {
    return getUsers().find(u => u.username === username && u.password === password);
}

function usernameExists(username) {
    return getUsers().some(u => u.username.toLowerCase() === username.toLowerCase());
}

function registerUser(data) {
    const users = getUsers();
    users.push({
        username: data.email,
        password: data.password,
        firstName: data.firstName,
        lastName: data.lastName,
        phone: data.phone,
        email: data.email,
        avatar: data.avatar || null,
        admin: false
    });
    setUsers(users);
}

function updateUserField(username, patch) {
    const users = getUsers();
    const idx = users.findIndex(u => u.username === username);
    if (idx < 0) return;
    users[idx] = { ...users[idx], ...patch };
    setUsers(users);
    return users[idx];
}

/* =================== FAVORITES =================== */

function getFavorites(username) {
    const all = readStore(STORE_KEYS.favorites, {});
    return all[username] || [];
}

function setFavorites(username, list) {
    const all = readStore(STORE_KEYS.favorites, {});
    all[username] = list;
    writeStore(STORE_KEYS.favorites, all);
}

function isFavorite(username, type, key) {
    return getFavorites(username).some(f => f.type === type && f.key === key);
}

function toggleFavorite(username, type, key) {
    const list = getFavorites(username);
    const idx = list.findIndex(f => f.type === type && f.key === key);
    if (idx >= 0) list.splice(idx, 1);
    else list.push({ type, key });
    setFavorites(username, list);
    return idx < 0;
}

