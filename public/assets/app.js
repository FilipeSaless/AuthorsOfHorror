function readStore(key, fallback) {
    try {
        const raw = localStorage.getItem(key);
        return raw ? JSON.parse(raw) : fallback;
    } catch { return fallback; }
}

function writeStore(key, value) {
    localStorage.setItem(key, JSON.stringify(value));
}

function seedStores() {
    if (!localStorage.getItem(STORE_KEYS.movies))    writeStore(STORE_KEYS.movies,    MOVIES);
    if (!localStorage.getItem(STORE_KEYS.books))     writeStore(STORE_KEYS.books,     BOOKS);
    if (!localStorage.getItem(STORE_KEYS.authors))   writeStore(STORE_KEYS.authors,   AUTHORS);
    if (!localStorage.getItem(STORE_KEYS.users))     writeStore(STORE_KEYS.users,     SEED_USERS);
    if (!localStorage.getItem(STORE_KEYS.favorites)) writeStore(STORE_KEYS.favorites, {});
    migrateCustomFlag();
}

// Marca como `custom` os itens já salvos que não fazem parte da lista-semente
// (filmes/livros adicionados pelo admin antes da criação do catálogo).
function migrateCustomFlag() {
    const tag = (seed, getList, setList) => {
        const seedTitles = new Set(seed.map(i => i.title));
        const list = getList();
        let changed = false;
        list.forEach(item => {
            if (!('custom' in item)) {
                item.custom = !seedTitles.has(item.title);
                changed = true;
            }
        });
        if (changed) setList(list);
    };
    tag(MOVIES, getMovies, setMovies);
    tag(BOOKS, getBooks, setBooks);
}

