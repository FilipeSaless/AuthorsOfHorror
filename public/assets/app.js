function loadFavoritesPage() {
    const container = document.getElementById('favoritesContainer');
    if (!container) return;

    const user = getUser();
    if (!user) {
        window.location.href = './index.html';
        return;
    }

    const renderList = () => {
        const favs = getFavorites(user.username);
        if (!favs.length) {
            container.innerHTML = '<p class="empty-state">Você ainda não possui itens favoritos cadastrados.</p>';
            return;
        }
        const movies = getMovies();
        const books = getBooks();
        const items = favs.map(f => {
            const list = f.type === 'movie' ? movies : books;
            const item = list.find(i => i.title === f.key);
            return item ? { ...item, _type: f.type } : null;
        }).filter(Boolean);

        if (!items.length) {
            container.innerHTML = '<p class="empty-state">Você ainda não possui itens favoritos cadastrados.</p>';
            return;
        }

        container.innerHTML = `
            <div class="favorites-grid">
                ${items.map(item => `
                    <article class="favorite-card">
                        <a href="./detalhes.html?type=${item._type}&title=${encodeURIComponent(item.title)}">
                            <img src="${item.image}" alt="${item.alt || item.title}">
                            <div class="favorite-info">
                                <h3>${item.title}</h3>
                                <p>${(item.description || '').slice(0, 140)}${(item.description || '').length > 140 ? '…' : ''}</p>
                            </div>
                        </a>
                        <button class="favorite-remove" type="button"
                                data-fav-type="${item._type}" data-fav-key="${encodeURIComponent(item.title)}">
                            Remover dos favoritos
                        </button>
                    </article>
                `).join('')}
            </div>
        `;
        container.querySelectorAll('.favorite-remove').forEach(btn => {
            btn.addEventListener('click', () => {
                toggleFavorite(user.username, btn.dataset.favType, decodeURIComponent(btn.dataset.favKey));
                renderList();
            });
        });
    };

    renderList();
}

