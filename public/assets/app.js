function loadCatalogPage() {
    const grid = document.getElementById('catalogGrid');
    if (!grid) return;

    const kind = grid.dataset.kind; // 'movie' ou 'book'
    const emptyEl = document.getElementById('catalogEmpty');
    // O catálogo reúne TODOS os itens: os padrão do site + os adicionados pelo admin.
    const items = kind === 'movie' ? getMovies() : getBooks();

    if (!items.length) {
        grid.style.display = 'none';
        if (emptyEl) emptyEl.style.display = '';
        return;
    }
    if (emptyEl) emptyEl.style.display = 'none';

    if (kind === 'movie') renderMovies(items, grid);
    else renderBooks(items, grid);

    setupCatalogSearch(items, kind, grid);
}

