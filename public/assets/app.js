function loadDetail() {
    const params = new URLSearchParams(window.location.search);
    const type = params.get('type');
    const key = params.get('title') || params.get('name');
    const container = document.getElementById('detailContainer');

    if (!type || !key) {
        container.innerHTML = '<p class="detail-error">Item não encontrado.</p>';
        return;
    }

    const movies = getMovies();
    const books = getBooks();
    const authors = getAuthors();
    const dataMap = { movie: movies, book: books, author: authors };
    const items = dataMap[type];
    if (!items) {
        container.innerHTML = '<p class="detail-error">Tipo desconhecido.</p>';
        return;
    }

    const matchField = type === 'author' ? 'name' : 'title';
    const item = items.find(i => i[matchField] === key);

    if (!item) {
        container.innerHTML = '<p class="detail-error">Item não encontrado.</p>';
        return;
    }

    if (type === 'author') {
        const typeByTitle = {};
        movies.forEach(m => { typeByTitle[m.title] = 'movie'; });
        books.forEach(b => { typeByTitle[b.title] = 'book'; });
        renderAuthorDetail(container, item, typeByTitle);
    } else if (type === 'book') {
        renderDetail(container, item, type, { movies, authors });
    } else {
        renderDetail(container, item, type);
    }
    bindFavoriteButtons(container);
}

